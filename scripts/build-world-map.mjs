// One-off generator for lib/world-map.ts (run: node scripts/build-world-map.mjs).
// Source: Natural Earth 1:110m admin-0 countries (public domain). Projected with Equal Earth,
// Antarctica dropped, coordinates rounded, so the app ships static SVG paths and no map library.
import { writeFile } from "node:fs/promises";

const SOURCE = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_admin_0_countries.geojson";
const WIDTH = 1000;

// Equal Earth (Šavrič, Patterson, Jenny 2018).
const A1 = 1.340264, A2 = -0.081106, A3 = 0.000893, A4 = 0.003796, M = Math.sqrt(3) / 2;
function project([lon, lat]) {
  const l = (lon * Math.PI) / 180, p = (lat * Math.PI) / 180;
  const t = Math.asin(M * Math.sin(p)), t2 = t * t, t6 = t2 * t2 * t2;
  const x = (l * Math.cos(t)) / (M * (A1 + 3 * A2 * t2 + t6 * (7 * A3 + 9 * A4 * t2)));
  const y = t * (A1 + A2 * t2 + t6 * (A3 + A4 * t2));
  return [x, y];
}

const geo = await (await fetch(SOURCE)).json();
const features = geo.features.filter((f) => f.properties.ISO_A2_EH !== "AQ");

const rings = (g) => (g.type === "Polygon" ? g.coordinates : g.coordinates.flat());
let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
for (const f of features) for (const ring of rings(f.geometry)) for (const pt of ring) {
  const [x, y] = project(pt);
  minX = Math.min(minX, x); maxX = Math.max(maxX, x); minY = Math.min(minY, y); maxY = Math.max(maxY, y);
}
const scale = WIDTH / (maxX - minX);
const height = Math.ceil((maxY - minY) * scale);
const toSvg = ([x, y]) => [Math.round((x - minX) * scale * 10) / 10, Math.round((maxY - y) * scale * 10) / 10];

const paths = [];
for (const f of features) {
  // ISO_A2 is "-99" for a few countries (France, Norway…); the _EH column fills those in.
  const iso = [f.properties.ISO_A2_EH, f.properties.ISO_A2].find((c) => /^[A-Z]{2}$/.test(c ?? ""));
  if (!iso) continue;
  // Relative commands in tenths of a unit, repeated points dropped: about half the size of absolute paths.
  const n = (v) => String(Math.round(v * 10) / 10).replace(/^(-?)0\./, "$1.");
  let d = "";
  for (const ring of rings(f.geometry)) {
    const pts = ring.map((pt) => toSvg(project(pt)));
    let [px, py] = pts[0];
    d += `M${n(px)} ${n(py)}l`;
    const steps = [];
    for (const [x, y] of pts.slice(1)) {
      const dx = Math.round((x - px) * 10) / 10, dy = Math.round((y - py) * 10) / 10;
      if (dx === 0 && dy === 0) continue;
      steps.push(`${n(dx)}${dy < 0 ? "" : " "}${n(dy)}`);
      px = Math.round((px + dx) * 10) / 10; py = Math.round((py + dy) * 10) / 10;
    }
    d += steps.join(" ").replace(/ -/g, "-") + "z";
  }
  paths.push([iso, d]);
}
paths.sort((a, b) => a[0].localeCompare(b[0]));

const out = `// Generated by scripts/build-world-map.mjs from Natural Earth 1:110m (public domain). Do not edit.
export const WORLD_VIEWBOX = "0 0 ${WIDTH} ${height}";
/** [ISO 3166-1 alpha-2, SVG path] per country, Equal Earth projection. */
export const WORLD_PATHS: readonly (readonly [string, string])[] = ${JSON.stringify(paths)};
`;
await writeFile(new URL("../lib/world-map.ts", import.meta.url), out);
console.log(`${paths.length} countries, ${(out.length / 1024).toFixed(0)} KB, viewBox 0 0 ${WIDTH} ${height}`);
